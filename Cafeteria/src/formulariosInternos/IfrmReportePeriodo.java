    public void consultar(){
        SimpleDateFormat formato = new SimpleDateFormat("dd/MM/yyyy");
        formato.setLenient(false);
        try{
            Date desde = formato.parse(txtDesde.getText().trim());
            Date hasta = formato.parse(txtHasta.getText().trim());
            if(desde.after(hasta)){
                JOptionPane.showMessageDialog(rootPane, "La fecha inicial no puede ser mayor a la final");
                return;
            }
            try (Connection con = DriverManager.getConnection(conexion.getUrl(),
                conexion.getUsername(), conexion.getPassword())) {
                DefaultTableModel modelo = new DefaultTableModel();
                PreparedStatement pstm = con.prepareCall("call ventasPeriodo(?,?)");
                pstm.setString(1, formato.format(desde));
                pstm.setString(2, formato.format(hasta));
                ResultSet rs = pstm.executeQuery();
                ResultSetMetaData rsmt = rs.getMetaData();
                for(int i = 1; i <= rsmt.getColumnCount(); i++){
                    modelo.addColumn(rsmt.getColumnLabel(i));
                }
                int totalVentas = 0;
                while(rs.next()){
                    Object[] filas = new Object[rsmt.getColumnCount()];
                    for(int i = 1; i <= rsmt.getColumnCount(); i++){
                        filas[i-1] = rs.getObject(i);
                    }
                    modelo.addRow(filas);
                    totalVentas += rs.getInt("Total");
                }
                TableReporte.setModel(modelo);
                lblTotal.setText("Total de ventas del periodo: " + totalVentas);
            } catch (SQLException e) {
                JOptionPane.showMessageDialog(rootPane, e.toString());
            }
        }catch(ParseException ex){
            JOptionPane.showMessageDialog(rootPane, "Fecha invalida. Use el formato dd/MM/yyyy");
        }
    }

